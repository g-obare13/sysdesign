/**
 * Parses and validates raw model text response into typed graph nodes and edges.
 *
 * @param raw - Raw string received from AI provider
 * @returns Parsed graph structure
 */
function parseAIResponse(raw: string): AIGraphResult {
  const cleaned = raw
    .replace(/```json\s*/gi, "")
    .replace(/```\s*/g, "")
    .trim();
  const parsed = JSON.parse(cleaned);
  if (!Array.isArray(parsed.nodes) || !Array.isArray(parsed.edges)) {
    throw new Error("AI response missing nodes or edges array");
  }
  return parsed as AIGraphResult;
}

/**
 * Converts raw AI generated nodes into ReactFlow diagram node entities.
 *
 * @param aiNodes - Array of raw AI nodes
 * @param mode - Active diagram mode
 * @returns Array of typed diagram nodes
 */
function toCanvasNodes(
  aiNodes: Array<AINode>,
  mode: "architecture" | "c4",
): Array<DiagramNode> {
  return aiNodes.map((n) => {
    const subtype = n.subtype.toLowerCase();
    const category = (SUBTYPE_CATEGORY[subtype] ??
      (mode === "c4" ? "c4" : "microservice")) as NodeMeta["category"];
    const icon = SUBTYPE_ICON[subtype] ?? "IconBox";
    return {
      id: n.id,
      type: "diagramNode",
      position: { x: n.x, y: n.y },
      data: {
        subtype,
        label: n.label,
        description: n.description,
        category,
        icon,
      } as NodeMeta,
    };
  });
}

/**
 * Converts raw AI generated edge connections into ReactFlow diagram edges.
 *
 * @param aiEdges - Array of raw AI edge links
 * @param mode - Active diagram mode
 * @returns Array of typed diagram edges
 */
function toCanvasEdges(
  aiEdges: Array<AIEdge>,
  mode: "architecture" | "c4",
): Array<DiagramEdge> {
  return aiEdges.map((e, i) => ({
    id: `ai-e-${i + 1}`,
    source: e.source,
    target: e.target,
    type: "smoothstep",
    label: e.label || undefined,
    data: mode === "c4" ? { label: e.label } : {},
    style: { stroke: "var(--border)", strokeWidth: 1.5 },
    markerEnd: { type: MarkerType.ArrowClosed, color: "var(--border)" },
  }));
}

