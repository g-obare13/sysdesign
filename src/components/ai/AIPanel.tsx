/** Raw node structure returned by the AI provider JSON response */
interface AINode {
  id: string;
  subtype: string;
  label: string;
  description: string;
  x: number;
  y: number;
}

/** Raw edge connection returned by the AI provider JSON response */
interface AIEdge {
  source: string;
  target: string;
  label: string;
}

/** Complete graph payload generated by the AI model */
interface AIGraphResult {
  nodes: Array<AINode>;
  edges: Array<AIEdge>;
}

